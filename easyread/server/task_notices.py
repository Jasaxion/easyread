"""Per-App, memory-only activity summaries. Never a scheduler or a durable log."""
from __future__ import annotations

import threading
import time
from contextlib import AbstractContextManager
from uuid import uuid4

from ..app.i18n import tr
from ..engines.engines import Cancelled

ACTIVE = frozenset(("queued", "running", "waiting"))
TERMINAL = frozenset(("completed", "failed", "cancelled", "interrupted"))


def notify(observer, *args, **kwargs):
    """Observers only take their own memory lock; failures never affect producers."""
    if observer is not None:
        try:
            return observer(*args, **kwargs)
        except Exception:
            pass
    return None


def text(value, limit=160):
    return " ".join(value.split())[:limit] if isinstance(value, str) else ""


def state_label(state):
    return {"queued": tr("排队中"), "running": tr("正在处理"), "waiting": tr("等待确认"),
            "completed": tr("完成"), "failed": tr("出错了"), "cancelled": tr("已取消"),
            "interrupted": tr("已中断")}[state]


class Notices:
    def __init__(self, root, *, history=30):
        from ..research.tasks import scope_id
        self.scope = scope_id(root)  # Resolve once, never on a monitor read.
        self.history = max(0, history)
        self._lock = threading.Lock()
        self._entries: dict[str, dict] = {}
        self._keys: dict[str, str] = {}
        # Paper writes release their file lock before publishing; delayed
        # callbacks must not replace a newer write or retry acceptance.
        self._orders: dict[str, int] = {}

    def publish(self, key: str, activity_kind: str, state: str, *, title="", paper_id="", project_id="",
                url="/research", stage_label="", message="", done=None, total=None,
                restart=False, only_existing=False, order=0):
        if state not in ACTIVE | TERMINAL:
            return None
        # Destinations are generated by adapters, never copied from producer URLs.
        if not (url == "/research" or url.startswith("/read/") or url.startswith("/workspaces?project=")):
            url = "/research"
        if "\\" in url or any(ord(c) < 32 for c in url):
            url = "/research"
        summary = {"kind": "activity", "activity_kind": text(activity_kind, 60), "state": state,
                   "title": text(title) or text(paper_id or project_id) or state_label(state),
                   "stage_label": text(stage_label) or state_label(state), "message": text(message, 240),
                   "url": url}
        if paper_id:
            summary["paper_id"] = text(paper_id, 200)
        if project_id:
            summary["project_id"] = text(project_id, 200)
        for name, value in (("done", done), ("total", total)):
            if type(value) is int and value >= 0:
                summary[name] = value
        with self._lock:
            identity = self._keys.get(key)
            previous = self._entries.get(identity)
            if order and order <= self._orders.get(key, 0):
                return dict(previous) if previous else None
            if order:
                self._orders[key] = order
            if only_existing and (previous is None or previous["state"] in TERMINAL):
                return dict(previous) if previous else None
            # Progress, settings writes and repeated idle summaries cannot unacknowledge.
            restart = restart or bool(previous and previous["state"] in TERMINAL and state in ACTIVE)
            if previous and not restart and all(previous.get(k) == v for k, v in summary.items()):
                return dict(previous)
            now = time.time()
            if previous and not restart:
                summary.update(id=identity, created=previous["created"], acknowledged=previous["acknowledged"])
            else:
                if identity:
                    self._entries.pop(identity, None)
                identity = "activity-" + uuid4().hex
                self._keys[key] = identity
                summary.update(id=identity, created=now, acknowledged=False)
            summary["updated"] = now
            self._entries[identity] = summary
            self._prune()
            return dict(summary)

    def _prune(self):
        recent = sorted((x for x in self._entries.values() if x["state"] in TERMINAL),
                        key=lambda x: x["updated"], reverse=True)
        for item in recent[self.history:]:
            self._entries.pop(item["id"], None)
        self._keys = {key: identity for key, identity in self._keys.items() if identity in self._entries}
        self._orders = {key: order for key, order in self._orders.items() if key in self._keys}

    def snapshot(self, *, scope=None):
        if scope is not None and scope != self.scope:
            return []
        with self._lock:
            return [dict(x) for x in sorted(self._entries.values(), key=lambda x: x["updated"], reverse=True)]

    def acknowledge(self, identity, *, scope=None):
        if scope is not None and scope != self.scope:
            return None
        with self._lock:
            item = self._entries.get(identity)
            if item is None or item["state"] not in TERMINAL:
                return None
            item["acknowledged"] = True
            return dict(item)

    def observe(self, source, identity, data, **kwargs):
        from .task_notice_sources import observe
        return observe(self, source, identity, data, **kwargs)


def monitor(app):
    from ..research import tasks
    notices = getattr(app, "notices", None)
    scope = notices.scope if notices is not None else tasks.scope_id(app.lib.root)
    return {"scope_id": scope, "tasks": tasks.list_tasks(scope=scope),
            "activities": notices.snapshot(scope=scope) if notices is not None else [],
            "token": getattr(app, "token", "")}


def acknowledge(app, identity, body):
    notices = getattr(app, "notices", None)
    if notices is None or ("scope_id" in body and body["scope_id"] != notices.scope):
        raise ValueError(tr("找不到这个研究工作。"))
    task = notices.acknowledge(identity, scope=notices.scope)
    if task is None:
        raise ValueError(tr("找不到这个研究工作。"))
    return {"task": task}


class RequestNotice(AbstractContextManager):
    """Explicit terminal markers also cover handlers that swallow stream errors."""
    def __init__(self, app, kind, *, paper_id="", title=""):
        from urllib.parse import quote
        self.notices = getattr(app, "notices", None)
        self.key = "request:" + uuid4().hex
        self.kind = kind
        self.fields = {"paper_id": paper_id, "title": title or paper_id,
                       "url": "/read/" + quote(paper_id, safe="") if paper_id else "/research"}
        self.finished = False

    def _publish(self, state):
        if self.notices is not None:
            notify(self.notices.publish, self.key, self.kind, state, **self.fields)

    def __enter__(self):
        self._publish("running")
        return self

    def finish(self, state):
        if not self.finished:
            self._publish(state)
            self.finished = True

    def __exit__(self, exc_type, exc, tb):
        if isinstance(exc, (Cancelled, BrokenPipeError, ConnectionResetError, ConnectionAbortedError)):
            self.finish("cancelled")
        elif exc is not None:
            self.finish("failed")
        else:
            self.finish("completed")
        return False
